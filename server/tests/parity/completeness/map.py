"""The completeness map: every group, every server RPC and every component type of the game,
against this server's code, its unit tests, the parity sweep and a late-game save.

    python3 map.py gen DATA_DIR [--cs CS_DIR] [--census census.json]    write MATRIX.csv, RPCS.csv,
                                                                        COMPONENTS.csv, MATRIX.md
    python3 map.py check                                               no game data: the files agree
                                                                        with each other and with the
                                                                        code (CI)
    python3 map.py numbers                                             the headline numbers, as
                                                                        docs/COMPLETENESS.md quotes them

DATA_DIR holds the game tables (netdata.json, gamedata.json, rpcs.json). SWEEP_START (environment) is
a start save for sweep.py gen: with it the sweep's own scripts are generated and the RPCs they send are
counted (RPCS.csv's sweep_sends); without it that column stays empty. CS_DIR is the game's
decompiled code, only to tell which component types do host-side work (kept in COMPONENTS.csv, so
a run without it reuses that). census.json is census.py's output for the save used as the driver;
it holds only group names and counts.

What each column means is written in MATRIX.md's head. Nothing here is a judgement: a cell is
found by searching the code, the tests and the sweep's own result files.
"""
import csv
import glob
import json
import os
import re
import sys
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
PARITY = os.path.dirname(HERE)
SERVER = os.path.abspath(os.path.join(PARITY, '..', '..'))
SRC = os.path.join(SERVER, 'src')


# ---- the code and its tests ---------------------------------------------------------------------

def rust_files():
    return sorted(glob.glob(f'{SRC}/**/*.rs', recursive=True)) + sorted(glob.glob(f'{SERVER}/tests/*.rs'))


def split_tests(path):
    """(code, tests) of a Rust file: tests are what follows `#[cfg(test)]` (or the whole file of
    a tests.rs / play_tests.rs / testkit.rs / tests/x.rs)."""
    text = open(path, encoding='utf-8').read()
    base = os.path.basename(path)
    if base in ('tests.rs', 'play_tests.rs', 'testkit.rs') or path.startswith(f'{SERVER}/tests/'):
        return '', text
    at = text.find('#[cfg(test)]')
    return (text, '') if at < 0 else (text[:at], text[at:])


def read_code():
    code, tests, where = {}, {}, {}
    for f in rust_files():
        rel = os.path.relpath(f, SERVER)
        c, t = split_tests(f)
        code[rel], tests[rel] = c, t
    return code, tests


def module_of(rel):
    """src/machines/growers.rs -> machines::growers"""
    p = rel[len('src/'):-3] if rel.startswith('src/') else rel
    return '::'.join(x for x in p.split('/') if x not in ('mod', 'main'))


def coverage_map():
    """coverage.txt -> (rpc tests, unhandled rpcs, module tests)"""
    rpc, unhandled, module = {}, {}, {}
    for line in open(f'{SRC}/coverage.txt', encoding='utf-8'):
        line = line.split('  #')[0].rstrip()
        if not line or line.startswith('#'):
            continue
        kind, name, *rest = line.split()
        if kind == 'rpc':
            rpc[name] = rest
        elif kind == 'unhandled':
            unhandled[name] = ' '.join(rest)
        elif kind in ('module', 'manual'):
            module[name] = rest
    return rpc, unhandled, module


def sweep_matrix():
    """SWEEP.matrix.md -> group -> {kind, interactions, scripts, result}"""
    out = {}
    for line in open(f'{PARITY}/SWEEP.matrix.md', encoding='utf-8'):
        if not line.startswith('| ') or line.startswith('| group') or line.startswith('|---'):
            continue
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) != 5 or '(state)' in cells[0] or '(save)' in cells[0]:
            continue
        name, kind, n, scripts, result = cells
        out[name] = {'kind': kind, 'interactions': int(n) if n.isdigit() else 0, 'scripts': scripts, 'result': result}
    return out


def classes_of(result):
    """'all match' -> '' ; 'create on the floor: b; deconstruct: d' -> 'b,d'"""
    if result in ('all match', ''):
        return ''
    found = sorted({m for part in result.split(';') for m in re.findall(r':\s*([a-e](?:/[a-e])*)\s*$', part.strip()) for m in m.split('/')})
    return ','.join(found)


def probe_rpcs():
    """RPC -> number of times a parity probe script sends it: the sweep's generated scripts
    (regenerated by sweep.py gen into a temp dir by the caller) and scripts/*.json."""
    count = Counter()
    for f in glob.glob(f'{PARITY}/scripts/*.json'):
        for s in json.load(open(f)).get('steps', []):
            if 'rpc' in s:
                count[s['rpc']] += 1
    return count


def sweep_rpcs(data_dir):
    """RPCs the generated sweep scripts send (sweep.py's own generator, no game process)."""
    import importlib.util
    import tempfile
    spec = importlib.util.spec_from_file_location('sweep', f'{PARITY}/sweep.py')
    sweep = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(sweep)
    count = Counter()
    start = os.environ.get('SWEEP_START')
    if not start or not os.path.exists(start):
        return count, False
    with tempfile.TemporaryDirectory() as out:
        argv, sys.argv = sys.argv, ['sweep.py', 'gen', data_dir, out, start]
        try:
            sweep.main()
        except SystemExit:
            pass
        finally:
            sys.argv = argv
        for f in glob.glob(f'{out}/sweep_*.json'):
            for s in json.load(open(f)).get('steps', []):
                if 'rpc' in s:
                    count[s['rpc']] += 1
    return count, True


# ---- generation ---------------------------------------------------------------------------------

HOST_FIELDS = ['class', 'host_checks', 'server_rpcs', 'client_rpcs', 'modules']
COMPONENT_FIELDS = ['component', 'groups', 'host_side', 'named_in_code', 'modules']
RPC_FIELDS = ['rpc', 'class', 'direction', 'handled', 'handler', 'unit_tests', 'parity_probe_sends', 'sweep_sends', 'note']
GROUP_FIELDS = ['group', 'kind', 'category', 'in_save', 'world_objects', 'in_inventories', 'planets', 'host_components', 'host_components_missing',
                'named_in_code', 'named_in_tests', 'family_tested', 'sweep_scripts', 'sweep_interactions', 'sweep_classes', 'sweep_result', 'status']


def load_tables(data_dir):
    n = json.load(open(f'{data_dir}/netdata.json'))
    gd = json.load(open(f'{data_dir}/gamedata.json'))
    rp = json.load(open(f'{data_dir}/rpcs.json'))
    kinds = {}
    for key, v in gd['assets'].items():
        k = key.split(':')[0]
        if k in ('GroupDataItem', 'GroupDataConstructible'):
            kinds[v['id']] = ('item', v.get('itemCategory')) if k == 'GroupDataItem' else ('constructible', v.get('groupCategory'))
    return n, gd, rp, kinds


# Component types the check "does host-side work" finds but that only ask a handled RPC (read in the
# game's code): not a gap.
CLIENT_ONLY = {'ActionnableShowInfos': 'a tooltip that asks WorldObjectAssociatedProxy.GetWorldObjectDetailsServerRpc'}


def host_side_components(types, cs_dir, previous):
    """Component type -> True when the game's code for it does host-side work or networks."""
    out = {}
    for t in types:
        if t in CLIENT_ONLY:
            out[t] = False
            continue
        f = os.path.join(cs_dir, t + '.cs') if cs_dir else ''
        if f and os.path.exists(f):
            out[t] = bool(re.search(r'\bIsServer\b|\bIsHost\b|GetIsHost|ServerRpc|ClientRpc|NetworkVariable', open(f, encoding='utf-8', errors='replace').read()))
        else:
            out[t] = previous.get(t, False)
    return out


def host_classes(cs_dir, code):
    """Every class of the game's code that checks IsServer/IsHost or carries RPCs, and the server
    modules that name it. Without CS_DIR the committed HOSTCLASSES.csv stands."""
    path = f'{HERE}/HOSTCLASSES.csv'
    if not cs_dir:
        return read_csv(path) if os.path.exists(path) else []
    rows = []
    for f in sorted(glob.glob(os.path.join(cs_dir, '*.cs'))):
        name = os.path.basename(f)[:-3]
        text = open(f, encoding='utf-8', errors='replace').read()
        host = len(re.findall(r'\bIsServer\b|\bIsHost\b|GetIsHost|IsMasterOrSolo', text))
        srpc, crpc = len(re.findall(r'\[ServerRpc', text)), len(re.findall(r'\[ClientRpc', text))
        if not (host or srpc or crpc):
            continue
        mods = sorted({module_of(p) for p, c in code.items() if re.search(r'\b' + re.escape(name) + r'\b', c)})
        rows.append({'class': name, 'host_checks': host, 'server_rpcs': srpc, 'client_rpcs': crpc, 'modules': ' '.join(mods[:6])})
    return rows


def gen(data_dir, cs_dir, census_path):
    n, gd, rp, kinds = load_tables(data_dir)
    code, tests = read_code()
    all_code = '\n'.join(code.values())
    all_tests = '\n'.join(tests.values())
    cov_rpc, cov_unhandled, cov_module = coverage_map()
    sweep = sweep_matrix()
    census = json.load(open(census_path))['groups'] if census_path and os.path.exists(census_path) else {}

    # components
    carrying = defaultdict(set)
    for g, p in gd['groupPrefabs'].items():
        for c in p['components']:
            carrying[c['type']].add(g)
    previous = {}
    if os.path.exists(f'{HERE}/COMPONENTS.csv'):
        previous = {r['component']: r['host_side'] == 'yes' for r in csv.DictReader(open(f'{HERE}/COMPONENTS.csv'))}
    host = host_side_components(sorted(carrying), cs_dir, previous)
    comp_rows, named = [], {}
    for t in sorted(carrying):
        mods = sorted({module_of(f) for f, c in code.items() if re.search(r'\b' + re.escape(t) + r'\b', c)})
        named[t] = bool(mods)
        comp_rows.append({'component': t, 'groups': len(carrying[t]), 'host_side': 'yes' if host[t] else 'no', 'named_in_code': 'yes' if mods else 'no', 'modules': ' '.join(mods[:6])})

    # groups
    layouts = gd['layouts']
    rows = []
    group_tests = {}
    for g in sorted(n['groups']):
        kind, cat = kinds.get(g, ('?', None))
        comps = sorted({c['type'] for c in gd['groupPrefabs'].get(g, {}).get('components', [])})
        behaviours = sorted({b['class'] for b in layouts.get(g, {}).get('behaviours', [])})
        hostc = [c for c in comps if host.get(c)]
        missing = [c for c in hostc if not named.get(c)]
        in_code = len(re.findall(r'"' + re.escape(g) + r'"', all_code))
        in_tests = len(re.findall(r'"' + re.escape(g) + r'"', all_tests))
        # a group is family-tested when a host-side component it carries is named in a module with unit tests
        fam = False
        for c in hostc:
            for r in comp_rows:
                if r['component'] == c and any(cov_module.get(m) for m in r['modules'].split()):
                    fam = True
        s = sweep.get(g)
        cen = census.get(g, {})
        if g not in gd['groupPrefabs'] and kind == 'constructible':
            status = 'no prefab in the game: nothing to host'
        elif missing:
            status = 'partly: host-side component not in the code (' + ' '.join(missing) + ')'
        else:
            status = 'implemented'
        rows.append({
            'group': g, 'kind': kind, 'category': cat or '', 'in_save': cen.get('total', ''), 'world_objects': cen.get('world', ''),
            'in_inventories': (cen.get('in_player', 0) + cen.get('in_vehicle', 0) + cen.get('in_structure', 0) + cen.get('in_unowned', 0)) if cen else '',
            'planets': ' '.join(f'{k}:{v}' for k, v in sorted(cen.get('by_planet', {}).items())),
            'host_components': ' '.join(hostc), 'host_components_missing': ' '.join(missing),
            'named_in_code': in_code, 'named_in_tests': in_tests, 'family_tested': 'yes' if fam else 'no',
            'sweep_scripts': s['scripts'] if s else '', 'sweep_interactions': s['interactions'] if s else 0,
            'sweep_classes': classes_of(s['result']) if s else '', 'sweep_result': (s['result'] if s else 'not in the sweep')[:160], 'status': status,
        })

    # RPCs
    probe = probe_rpcs()
    swp, have_sweep = sweep_rpcs(data_dir)
    rpc_rows = []
    for r in sorted(rp.values(), key=lambda r: r['name']):
        name, to = r['name'], r['to']
        if to == 'server':
            handled = name not in cov_unhandled
            handler = ''
            files = [module_of(f) for f, c in code.items() if f.startswith('src/') and f'"{name}"' in c]
            if files:
                handler = ' '.join(sorted(set(files))[:3])
            tests_ = cov_rpc.get(name, [])
            rpc_rows.append({'rpc': name, 'class': name.split('.')[0], 'direction': 'server', 'handled': 'yes' if handled else 'no', 'handler': handler,
                             'unit_tests': len(tests_), 'parity_probe_sends': probe.get(name, 0), 'sweep_sends': swp.get(name, 0) if have_sweep else '',
                             'note': cov_unhandled.get(name, '')})
        else:
            short = name.split('.')[1]
            files = [module_of(f) for f, c in code.items() if f.startswith('src/') and (f'"{name}"' in c)]
            rpc_rows.append({'rpc': name, 'class': name.split('.')[0], 'direction': 'client', 'handled': 'sent' if files else 'not sent by name', 'handler': ' '.join(sorted(set(files))[:3]),
                             'unit_tests': '', 'parity_probe_sends': '', 'sweep_sends': '', 'note': ''})
    return rows, rpc_rows, comp_rows, have_sweep, host_classes(cs_dir, code)


def write_csv(path, fields, rows):
    with open(path, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fields, lineterminator='\n')
        w.writeheader()
        w.writerows(rows)


def percent(a, b):
    return f'{a} of {b} ({100 * a / b:.0f} %)' if b else '0'


def summary(rows, rpc_rows):
    """The headline numbers, from the rows alone (check recomputes them from the files)."""
    real = [r for r in rows if not r['status'].startswith('no prefab')]
    out = {'groups': len(rows), 'groups_without_prefab': len(rows) - len(real), 'groups_in_save': len([r for r in rows if r['in_save'] not in ('', 0, '0')])}
    for kind in ('item', 'constructible'):
        k = [r for r in real if r['kind'] == kind]
        out[f'{kind}s'] = len(k)
        out[f'{kind}s_implemented'] = len([r for r in k if r['status'] == 'implemented'])
        out[f'{kind}s_named_in_unit_tests'] = len([r for r in k if int(r['named_in_tests']) > 0])
        out[f'{kind}s_family_unit_tested'] = len([r for r in k if int(r['named_in_tests']) > 0 or r['family_tested'] == 'yes'])
        ok = [r for r in k if r['sweep_result'] != 'not in the sweep' and not r['sweep_result'].startswith('build: none')]
        out[f'{kind}s_parity_checked'] = len(ok)
        out[f'{kind}s_parity_with_a_bug_class'] = len([r for r in ok if 'a' in r['sweep_classes'].split(',')])
    srv = [r for r in rpc_rows if r['direction'] == 'server']
    handled = [r for r in srv if r['handled'] == 'yes']
    tested = [r for r in handled if int(r['unit_tests']) > 0]
    parity = [r for r in handled if int(r['parity_probe_sends']) > 0 or (r['sweep_sends'] != '' and int(r['sweep_sends']) > 0) or r['rpc'] == 'PlayerMainController.PlayerReadyServerRpc']
    out.update({'server_rpcs': len(srv), 'server_rpcs_handled': len(handled), 'server_rpcs_unit_tested': len(tested), 'server_rpcs_parity_checked': len(parity)})
    fam = defaultdict(list)
    for r in srv:
        fam[r['class']].append(r)
    out['rpc_families'] = len(fam)
    out['rpc_families_fully_handled'] = len([c for c, v in fam.items() if all(r['handled'] == 'yes' for r in v)])
    out['rpc_families_fully_unit_tested'] = len([c for c, v in fam.items() if all(int(r['unit_tests'] or 0) > 0 for r in v if r['handled'] == 'yes')])
    out['rpc_families_fully_parity_checked'] = len([c for c, v in fam.items() if all(r in parity for r in v if r['handled'] == 'yes')])
    cli = [r for r in rpc_rows if r['direction'] == 'client']
    out['client_rpcs'] = len(cli)
    out['client_rpcs_sent_by_name'] = len([r for r in cli if r['handled'] == 'sent'])
    return out


def write_md(path, rows, rpc_rows, comp_rows, have_sweep, s, host_rows=()):
    L = []
    L.append('# Completeness matrices\n')
    L.append('Generated by `map.py gen` (regenerate it, do not edit). One row per group of the game, per RPC and per')
    L.append('component type, found by searching this server\'s code and tests, the parity sweep\'s own result files')
    L.append('and a census of a late-game save (group names and counts only).\n')
    L.append('Columns:\n')
    L.append('- **status**: `implemented` when every component the prefab carries that does host-side work in the game is named')
    L.append('  in the server\'s code; `partly` otherwise; `no prefab` for the groups the game has no prefab for.')
    L.append('- **tests**: `named` = the group id is written in a unit test; `family` = a component it carries is in a module with unit tests.')
    L.append('- **parity**: the sweep (`SWEEP.md`) ran the group on the real game host and on this server: the classes left')
    L.append('  (a: bug, b: deliberate, c: new safety rule, d: the game\'s randomness or timing, e: not comparable).')
    L.append('- **save**: objects of the group in the late-game save (in the world / in inventories).\n')
    L.append('## Numbers\n')
    for k, v in s.items():
        L.append(f'- {k}: {v}')
    L.append('')
    L.append('## Groups the late-game save never has\n')
    for kind in ('constructible', 'item'):
        absent = [r['group'] for r in rows if r['kind'] == kind and r['in_save'] in ('', 0, '0')]
        L.append(f'{kind}s ({len(absent)}): ' + ', '.join(absent) + '\n')
    L.append('## Groups\n')
    L.append('| group | kind | status | tests | parity | save (world/inv) | sweep scripts |')
    L.append('|---|---|---|---|---|---|---|')
    for r in rows:
        tests_ = 'named' if int(r['named_in_tests']) else ('family' if r['family_tested'] == 'yes' else '-')
        parity = 'not in sweep' if r['sweep_result'] == 'not in the sweep' else ('match' if r['sweep_result'] == 'all match' else r['sweep_classes'] or r['sweep_result'][:30])
        save = '-' if r['in_save'] in ('', 0, '0') else f"{r['world_objects']}/{r['in_inventories']}"
        L.append(f"| {r['group']} | {r['kind']} | {r['status'].split(':')[0]} | {tests_} | {parity} | {save} | {r['sweep_scripts'][:60]} |")
    L.append('')
    L.append('## Server RPCs\n')
    L.append('| RPC | handled | unit tests | probe scripts | sweep | handler |')
    L.append('|---|---|---|---|---|---|')
    for r in rpc_rows:
        if r['direction'] == 'server':
            L.append(f"| {r['rpc']} | {r['handled']} | {r['unit_tests']} | {r['parity_probe_sends']} | {r['sweep_sends']} | {r['handler'] or r['note'][:60]} |")
    L.append('')
    L.append('## Client RPCs (what the server sends)\n')
    L.append('| RPC | sent by name | in |')
    L.append('|---|---|---|')
    for r in rpc_rows:
        if r['direction'] == 'client':
            L.append(f"| {r['rpc']} | {r['handled']} | {r['handler']} |")
    L.append('')
    L.append('## Component types\n')
    L.append('| component | groups | host-side work in the game | named in the code | modules |')
    L.append('|---|---|---|---|---|')
    for r in comp_rows:
        L.append(f"| {r['component']} | {r['groups']} | {r['host_side']} | {r['named_in_code']} | {r['modules']} |")
    L.append('')
    L.append('## Classes of the game that act on the host or carry RPCs\n')
    L.append('Every class of the game\'s code that tests IsServer/IsHost or has a ServerRpc/ClientRpc, and the modules of this')
    L.append('server that name it (none: nothing in this server names it).\n')
    L.append('| class | host checks | server RPCs | client RPCs | named in |')
    L.append('|---|---|---|---|---|')
    for r in host_rows:
        L.append(f"| {r['class']} | {r['host_checks']} | {r['server_rpcs']} | {r['client_rpcs']} | {r['modules'] or 'none'} |")
    open(path, 'w', encoding='utf-8').write('\n'.join(L) + '\n')


def read_csv(path):
    return list(csv.DictReader(open(path, encoding='utf-8')))


def check():
    """No game data: the committed files agree with each other and the code."""
    errors = []
    rows, rpc_rows, comp_rows = (read_csv(f'{HERE}/{n}.csv') for n in ('MATRIX', 'RPCS', 'COMPONENTS'))
    cov_rpc, cov_unhandled, cov_module = coverage_map()
    code, tests = read_code()
    # every RPC the map lists as handled is in coverage.txt with tests, and the other way round
    for r in rpc_rows:
        if r['direction'] != 'server':
            continue
        if (r['handled'] == 'yes') != (r['rpc'] not in cov_unhandled):
            errors.append(f"RPCS.csv: {r['rpc']} handled={r['handled']} but coverage.txt says otherwise")
        if r['handled'] == 'yes' and len(cov_rpc.get(r['rpc'], [])) != int(r['unit_tests']):
            errors.append(f"RPCS.csv: {r['rpc']} unit_tests {r['unit_tests']} != coverage.txt {len(cov_rpc.get(r['rpc'], []))}")
    listed = {r['rpc'] for r in rpc_rows}
    for name in list(cov_rpc) + list(cov_unhandled):
        if name not in listed:
            errors.append(f'coverage.txt lists {name}, RPCS.csv does not (regenerate the map)')
    # the sweep matrix and the map list the same groups
    sweep = sweep_matrix()
    for r in rows:
        if r['sweep_result'] != 'not in the sweep' and r['group'] not in sweep:
            errors.append(f"MATRIX.csv: {r['group']} has a sweep result, SWEEP.matrix.md has no row")
    # the numbers in docs/COMPLETENESS.md are the files' numbers
    doc = os.path.join(SERVER, '..', 'docs', 'COMPLETENESS.md')
    s = summary(rows, rpc_rows)
    if os.path.exists(doc):
        text = open(doc, encoding='utf-8').read()
        m = re.search(r'<!-- numbers:begin -->(.*?)<!-- numbers:end -->', text, re.S)
        if not m:
            errors.append('docs/COMPLETENESS.md has no numbers block')
        else:
            for k, v in s.items():
                if f'{k}: {v}\n' not in m.group(1) + '\n':
                    errors.append(f'docs/COMPLETENESS.md: {k} is not {v}')
    for e in errors:
        print(e)
    print(f"{len(rows)} groups, {len(rpc_rows)} RPCs, {len(comp_rows)} components; {len(errors)} problem(s)")
    return 1 if errors else 0


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return 2
    if args[0] == 'check':
        return check()
    if args[0] == 'numbers':
        for k, v in summary(read_csv(f'{HERE}/MATRIX.csv'), read_csv(f'{HERE}/RPCS.csv')).items():
            print(f'- {k}: {v}')
        return 0
    if args[0] == 'gen':
        data_dir = args[1]
        cs = args[args.index('--cs') + 1] if '--cs' in args else None
        census = args[args.index('--census') + 1] if '--census' in args else f'{HERE}/census.json'
        rows, rpc_rows, comp_rows, have_sweep, host_rows = gen(data_dir, cs, census)
        write_csv(f'{HERE}/HOSTCLASSES.csv', HOST_FIELDS, host_rows)
